    'public.export_sensor_chunk(timestamptz, timestamptz, bigint, int, text, text)',
    'public.cleanup_sensor_readings(int)',
    'public.dev_reset()'
  ] loop
    execute format('revoke all on function %s from public, anon, authenticated', f);
    execute format('grant execute on function %s to service_role', f);
  end loop;
end $$;

