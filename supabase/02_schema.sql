-- 3.1 reserve_feed -----------------------------------------------------------
-- Locks feeder_settings and the trigger_sources row, then checks in order:
--   source enabled -> quiet hours (sensor sources only) -> per-source cooldown
--   -> daily maximum -> empty hopper.
-- On success it decrements remaining_portions (never below 0), bumps the
-- daily counter and sets last_triggered_at, all in one transaction.
--
-- Daily maximum: counted with daily_used_portions (reset when the local date in
-- the configured time zone changes). This equals "sum of portions dispensed
-- today" but is race-free, because concurrent feeds from different sources are
-- serialised by the row lock before their feed_events rows exist.
--
-- Empty hopper:
--   skip_when_empty = true  -> skip if remaining < requested.
--   skip_when_empty = false -> partial dispense of what is left; if the tracked
--                              level is already 0 the requested portions are sent
--                              anyway (tracking is open-loop) and the level stays 0.
create function public.reserve_feed(
  p_source   text,
  p_portions int default null,
  p_now      timestamptz default now()
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  s            public.feeder_settings%rowtype;
  t            public.trigger_sources%rowtype;
  v_requested  int;
  v_today      date;
  v_local_time time;
  v_reason     text;
  v_retry_ms   int;
  v_log_skip   boolean;
  v_dispense   int;
  v_decrement  int;
begin
  select * into s from public.feeder_settings where id = 1 for update;
  if not found then
    raise exception 'feeder_settings row (id = 1) is missing';
  end if;

  select * into t from public.trigger_sources where source = p_source for update;
  if not found then
    return jsonb_build_object('ok', false, 'reason', 'UNKNOWN_SOURCE');
  end if;

  v_requested  := greatest(1, coalesce(p_portions, t.portions_per_trigger));
  v_today      := (p_now at time zone s.timezone)::date;
  v_local_time := (p_now at time zone s.timezone)::time;

  if s.daily_used_date is distinct from v_today then
    update public.feeder_settings
       set daily_used_date = v_today, daily_used_portions = 0
     where id = 1
    returning * into s;
  end if;

  if not t.enabled then
    v_reason := 'SKIPPED_DISABLED';
  elsif p_source in ('ESP32_SENSOR', 'PHONE_SENSOR')
        and s.quiet_hours_start is not null
        and s.quiet_hours_end is not null
        and s.quiet_hours_start <> s.quiet_hours_end
        and (
          (s.quiet_hours_start < s.quiet_hours_end
             and v_local_time >= s.quiet_hours_start and v_local_time < s.quiet_hours_end)
          or
          (s.quiet_hours_start > s.quiet_hours_end
             and (v_local_time >= s.quiet_hours_start or v_local_time < s.quiet_hours_end))
        ) then
    v_reason := 'SKIPPED_QUIET_HOURS';
  elsif t.last_triggered_at is not null
        and t.cooldown_seconds > 0
        and p_now < t.last_triggered_at + make_interval(secs => t.cooldown_seconds) then
    v_reason := 'SKIPPED_COOLDOWN';
    v_retry_ms := greatest(1, ceil(extract(epoch from (
                    t.last_triggered_at + make_interval(secs => t.cooldown_seconds) - p_now)) * 1000)::int);
  elsif s.daily_used_portions + v_requested > s.daily_max_portions then
    v_reason := 'SKIPPED_DAILY_LIMIT';
  elsif s.skip_when_empty and s.remaining_portions < v_requested then
    v_reason := 'SKIPPED_EMPTY';
  end if;

  if v_reason is not null then
    -- Manual and scheduled skips are always logged. Sensor skips are logged at
    -- most once per max(cooldown, 5 s) so a vibrating sensor cannot flood the log.
    v_log_skip := p_source in ('MANUAL', 'SCHEDULE')
                  or t.last_skip_logged_at is null
                  or p_now >= t.last_skip_logged_at + make_interval(secs => greatest(t.cooldown_seconds, 5));
    if v_log_skip then
      update public.trigger_sources set last_skip_logged_at = p_now where source = p_source;
    end if;

    return jsonb_build_object(
      'ok', false,
      'reason', v_reason,
      'retry_after_ms', v_retry_ms,
      'log_skip', v_log_skip,
      'portions_requested', v_requested,
      'portions_reserved', 0,
      'portions_decremented', 0,
      'remaining_after', s.remaining_portions,
      'capacity_portions', s.capacity_portions,
      'daily_used_portions', s.daily_used_portions,
      'daily_max_portions', s.daily_max_portions,
      'simulation_mode', s.simulation_mode,
      'calibration_id', s.active_calibration_id
    );
  end if;

  if s.remaining_portions >= v_requested then
    v_dispense := v_requested;
    v_decrement := v_requested;
  elsif s.remaining_portions > 0 then
    v_dispense := s.remaining_portions;           -- partial (only when skip_when_empty = false)
    v_decrement := s.remaining_portions;
  else
    v_dispense := v_requested;                    -- tracked level already 0, skip disabled
    v_decrement := 0;
  end if;

  update public.feeder_settings
     set remaining_portions  = greatest(0, remaining_portions - v_decrement),
         daily_used_portions = daily_used_portions + v_dispense,
         updated_at          = p_now
   where id = 1
  returning * into s;

  update public.trigger_sources set last_triggered_at = p_now where source = p_source;

  return jsonb_build_object(
    'ok', true,
    'reason', null,
    'retry_after_ms', null,
    'log_skip', false,
    'portions_requested', v_requested,
    'portions_reserved', v_dispense,
    'portions_decremented', v_decrement,
    'remaining_after', s.remaining_portions,
    'capacity_portions', s.capacity_portions,
    'daily_used_portions', s.daily_used_portions,
    'daily_max_portions', s.daily_max_portions,
    'simulation_mode', s.simulation_mode,
    'calibration_id', s.active_calibration_id
  );
end;
$$;

-- 3.2 refund_feed -------------------------------------------------------------
-- Returns undispensed portions after a failed feeder call, and clears the
-- source's cooldown so the user can retry immediately.
--   p_portions  = portions to add back to the hopper (what was decremented)
--   p_dispensed = portions to remove from today's counter (defaults to p_portions)
create function public.refund_feed(p_source text, p_portions int, p_dispensed int default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  s public.feeder_settings%rowtype;
begin
  update public.feeder_settings
     set remaining_portions  = least(capacity_portions, remaining_portions + greatest(0, p_portions)),
         daily_used_portions = greatest(0, daily_used_portions - greatest(0, coalesce(p_dispensed, p_portions))),
         updated_at          = now()
   where id = 1
  returning * into s;

  update public.trigger_sources set last_triggered_at = null where source = p_source;

  return jsonb_build_object('remaining_after', s.remaining_portions);
end;
$$;

-- 3.3 refill_hopper -----------------------------------------------------------
-- Records a refill and resolves low-food / empty alerts that no longer apply.
create function public.refill_hopper(
  p_portions_after int,
  p_grams_measured numeric default null,
  p_note           text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  s        public.feeder_settings%rowtype;
  v_before int;
  v_id     bigint;
  v_keys   text[] := '{}';
  v_resolved jsonb;
begin
  select * into s from public.feeder_settings where id = 1 for update;
  if p_portions_after is null or p_portions_after < 0 or p_portions_after > s.capacity_portions then
    raise exception 'Portions after refill must be between 0 and %', s.capacity_portions;
  end if;

  v_before := s.remaining_portions;

  insert into public.refill_events (portions_before, portions_after, grams_added_measured, note)
  values (v_before, p_portions_after, p_grams_measured, nullif(trim(p_note), ''))
  returning id into v_id;

  update public.feeder_settings
     set remaining_portions = p_portions_after, updated_at = now()
   where id = 1;

  if p_portions_after > 0 then
    v_keys := array_append(v_keys, 'hopper_empty');
  end if;
  if p_portions_after * 100 > s.low_food_threshold_percent * s.capacity_portions then
    v_keys := array_append(v_keys, 'low_food');
  end if;

  with r as (
    update public.notifications
       set status = 'resolved', resolved_at = now()
     where status = 'active' and dedupe_key = any (v_keys)
    returning id, type, dedupe_key
  )
  select coalesce(jsonb_agg(jsonb_build_object('id', id, 'type', type, 'dedupe_key', dedupe_key)), '[]'::jsonb)
    into v_resolved
    from r;

  return jsonb_build_object(
    'refill_id', v_id,
    'portions_before', v_before,
    'portions_after', p_portions_after,
    'resolved', v_resolved
  );
end;
$$;

-- 3.4 apply_calibration ---------------------------------------------------------
-- Inserts a new calibration version and makes it active. Every later feed
-- stores this calibration_id, so earlier history keeps its original values.
create function public.apply_calibration(
  p_grams_per_portion numeric,
  p_sd                numeric default null,
  p_sample_count      int default null,
  p_capacity_portions int default null,
  p_notes             text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  s    public.feeder_settings%rowtype;
  v_id bigint;
  v_capacity int;
begin
  select * into s from public.feeder_settings where id = 1 for update;
  v_capacity := coalesce(p_capacity_portions, s.capacity_portions);

  insert into public.calibrations (grams_per_portion, sd, sample_count, capacity_portions, notes)
  values (p_grams_per_portion, p_sd, p_sample_count, v_capacity, nullif(trim(p_notes), ''))
  returning id into v_id;

  update public.feeder_settings
     set grams_per_portion     = p_grams_per_portion,
         grams_per_portion_sd  = p_sd,
         active_calibration_id = v_id,
         capacity_portions     = v_capacity,
         remaining_portions    = least(remaining_portions, v_capacity),
         updated_at            = now()
   where id = 1;

  return jsonb_build_object('calibration_id', v_id);
end;
$$;

-- 3.5 raise_notification --------------------------------------------------------
-- Inserts an alert unless an ACTIVE alert with the same dedupe key exists.
-- Returns the new id, or null when it was a duplicate.
create function public.raise_notification(
  p_type       text,
  p_severity   text,
  p_message    text,
  p_dedupe_key text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
begin
  insert into public.notifications (type, severity, message, dedupe_key)
  values (p_type, p_severity, p_message, p_dedupe_key)
  on conflict (dedupe_key) where status = 'active' do nothing
  returning id into v_id;
  return v_id;
end;
$$;

-- 3.6 ingest_telemetry ------------------------------------------------------------
-- Inserts a whole ESP32 batch and updates the heartbeat in ONE database call.
-- recorded_at = server receive time - (largest offset in batch - sample offset),
-- so the newest sample is stamped with the receive time and none are in the future.
create function public.ingest_telemetry(
  p_device_id text,
  p_rssi      int,
  p_firmware  text,
  p_ip        text,
  p_samples   jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_now      timestamptz := now();
  v_batch    uuid := gen_random_uuid();
  v_max      numeric;
  v_inserted int;
  v_last_id  bigint;
begin
  select coalesce(max(coalesce((e ->> 'offsetMs')::numeric, 0)), 0)
    into v_max
    from jsonb_array_elements(p_samples) e;

  with ins as (
    insert into public.sensor_readings
      (device_id, recorded_at, ax, ay, az, dynamic_g_mean, dynamic_g_peak, rssi, batch_id)
    select
      p_device_id,
      v_now - make_interval(secs => (v_max - coalesce((e ->> 'offsetMs')::numeric, 0)) / 1000.0),
      (e ->> 'ax')::real,
      (e ->> 'ay')::real,
      (e ->> 'az')::real,
      (e ->> 'gMean')::real,
      (e ->> 'gPeak')::real,
      p_rssi,
      v_batch
    from jsonb_array_elements(p_samples) e
    returning id
  )
  select count(*), max(id) into v_inserted, v_last_id from ins;

  insert into public.device_heartbeats (device_id, last_seen_at, last_rssi, firmware, ip)
  values (p_device_id, v_now, p_rssi, p_firmware, p_ip)
  on conflict (device_id) do update
     set last_seen_at = excluded.last_seen_at,
         last_rssi    = excluded.last_rssi,
         firmware     = coalesce(excluded.firmware, public.device_heartbeats.firmware),
         ip           = coalesce(excluded.ip, public.device_heartbeats.ip);

  return jsonb_build_object('inserted', v_inserted, 'last_id', v_last_id, 'batch_id', v_batch, 'received_at', v_now);
end;
$$;

-- 3.7 sensor_buckets: server-side downsampling for the 10 min / 1 h views ---------
create function public.sensor_buckets(
  p_device_id      text,
  p_from           timestamptz,
  p_to             timestamptz,
  p_bucket_seconds int
)
returns table (
  bucket         timestamptz,
  ax             real,
  ay             real,
  az             real,
  dynamic_g_mean real,
  dynamic_g_peak real,
  n              int
)
language sql
stable
security definer
set search_path = public
as $$
  select
    date_bin(make_interval(secs => greatest(p_bucket_seconds, 1)), r.recorded_at, timestamptz '2000-01-01') as bucket,
    avg(r.ax)::real,
    avg(r.ay)::real,
    avg(r.az)::real,
    avg(r.dynamic_g_mean)::real,
    max(r.dynamic_g_peak)::real,
    count(*)::int
  from public.sensor_readings r
  where r.device_id = p_device_id
    and r.recorded_at >= p_from
    and r.recorded_at <  p_to
  group by 1
  order by 1;
$$;

-- 3.8 sensor_stats: mean, peak, p95 and threshold crossings for a range ------------
create function public.sensor_stats(
  p_device_id text,
  p_from      timestamptz,
  p_to        timestamptz,
  p_threshold numeric
)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  with r as (
    select
      dynamic_g_mean,
      dynamic_g_peak,
      lag(dynamic_g_peak) over (order by recorded_at, id) as prev_peak
    from public.sensor_readings
    where device_id = p_device_id
      and recorded_at >= p_from
      and recorded_at <  p_to
  )
  select jsonb_build_object(
    'count',     count(*),
    'mean',      avg(dynamic_g_mean),
    'peak',      max(dynamic_g_peak),
    'p95',       percentile_cont(0.95) within group (order by dynamic_g_peak),
    'crossings', count(*) filter (
                   where p_threshold is not null
                     and dynamic_g_peak >= p_threshold
                     and (prev_peak is null or prev_peak < p_threshold))
  )
  from r;
$$;

-- 3.9 export_sensor_chunk: CSV / JSON generated inside Postgres -------------------
-- The Worker streams the export chunk by chunk (keyset pagination on id), so
-- large ranges never sit in Worker memory and Worker CPU time stays low.
create function public.export_sensor_chunk(
  p_from     timestamptz,
  p_to       timestamptz,
  p_after_id bigint,
  p_limit    int,
  p_tz       text,
  p_format   text
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_chunk   text;
  v_last_id bigint;
  v_n       int;
begin
  with page as (
    select *
    from public.sensor_readings
    where recorded_at >= p_from
      and recorded_at <  p_to
      and id > coalesce(p_after_id, 0)
    order by id
    limit greatest(1, least(p_limit, 50000))
  ),
  rendered as (
    select
      id,
      case when p_format = 'json' then
        jsonb_build_object(
          'id', id,
          'recorded_at', to_char(recorded_at at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
          'recorded_at_local', to_char(recorded_at at time zone p_tz, 'YYYY-MM-DD HH24:MI:SS.MS'),
          'device_id', device_id,
          'ax', ax, 'ay', ay, 'az', az,
          'dynamic_g_mean', dynamic_g_mean,
          'dynamic_g_peak', dynamic_g_peak,
          'rssi', rssi
        )::text
      else
        concat_ws(',',
          id,
          to_char(recorded_at at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
          to_char(recorded_at at time zone p_tz, 'YYYY-MM-DD HH24:MI:SS.MS'),
          '"' || replace(device_id, '"', '""') || '"',
          coalesce(ax::text, ''), coalesce(ay::text, ''), coalesce(az::text, ''),
          coalesce(dynamic_g_mean::text, ''), coalesce(dynamic_g_peak::text, ''),
          coalesce(rssi::text, '')
        )
      end as line
    from page
  )
  select
    string_agg(line, case when p_format = 'json' then E',\n' else E'\n' end order by id),
    max(id),
    count(*)
  into v_chunk, v_last_id, v_n
  from rendered;

  return jsonb_build_object('chunk', coalesce(v_chunk, ''), 'last_id', v_last_id, 'n', coalesce(v_n, 0));
end;
$$;

-- 3.10 cleanup_sensor_readings: retention (called hourly from the cron job) --------
create function public.cleanup_sensor_readings(p_days int)
returns int
language plpgsql
security definer
set search_path = public
as $$
declare
  v_deleted int;
begin
  -- Filter by device (every device that has posted has a heartbeat row) so the
  -- (device_id, recorded_at) index is used instead of a full table scan.
  delete from public.sensor_readings r
   where r.device_id in (select device_id from public.device_heartbeats)
     and r.recorded_at < now() - make_interval(days => greatest(p_days, 1));
  get diagnostics v_deleted = row_count;
  return v_deleted;
end;
$$;

-- 3.11 dev_reset: Settings -> Developer tools -> Reset database --------------------
-- Clears v2 event data. Keeps settings, trigger sources, schedules, calibrations
-- and every legacy_* table. Refills the tracked hopper to capacity.
create function public.dev_reset()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  truncate table public.feed_events, public.refill_events, public.sensor_readings,
                 public.notifications, public.device_heartbeats restart identity;
  update public.feeder_settings
     set remaining_portions = capacity_portions,
         daily_used_portions = 0,
         daily_used_date = null,
         updated_at = now()
   where id = 1;
  update public.trigger_sources set last_triggered_at = null, last_skip_logged_at = null;
  return jsonb_build_object('ok', true);
end;
$$;

-- Lock all functions down to the service role.
do $$
declare
  f text;
begin
  foreach f in array array[
    'public.reserve_feed(text, int, timestamptz)',
    'public.refund_feed(text, int, int)',
    'public.refill_hopper(int, numeric, text)',
    'public.apply_calibration(numeric, numeric, int, int, text)',
    'public.raise_notification(text, text, text, text)',
    'public.ingest_telemetry(text, int, text, text, jsonb)',
    'public.sensor_buckets(text, timestamptz, timestamptz, int)',
