-- 1. Table: feeder_state (single row, id = 1)
create table if not exists public.feeder_state (
  id int primary key default 1 check (id = 1),
  remaining_grams numeric not null default 60.0,
  max_capacity_grams numeric not null default 60.0,
  grams_per_portion numeric not null default 1.5,
  cooldown_seconds int not null default 5,
  simulation_mode boolean not null default false,
  last_feed_at timestamptz null,
  updated_at timestamptz not null default now()
);

insert into public.feeder_state (
  id,
  remaining_grams,
  max_capacity_grams,
  grams_per_portion,
  cooldown_seconds,
  simulation_mode,
  last_feed_at,
  updated_at
) values (
  1, 60.0, 60.0, 1.5, 5, false, null, now()
)
on conflict (id) do nothing;

