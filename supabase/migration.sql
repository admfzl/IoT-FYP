-- 4. Atomic Postgres RPC Functions

-- 4.1 reserve_portion()
-- Locks feeder_state row (id = 1). If last_feed_at is within cooldown_seconds,
-- returns cooldown = true and retry_after_ms without modifying state.
-- Otherwise decrements remaining_grams atomically, updates last_feed_at, and returns cooldown = false.
create or replace function public.reserve_portion()
returns table (
  cooldown boolean,
  retry_after_ms int,
  remaining_grams numeric,
  max_capacity_grams numeric,
  grams_per_portion numeric,
  cooldown_seconds int,
  simulation_mode boolean,
  last_feed_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_state public.feeder_state%rowtype;
  v_elapsed_ms numeric;
  v_cooldown_ms numeric;
begin
  select * into v_state
  from public.feeder_state
  where id = 1
  for update;

  if not found then
    insert into public.feeder_state (id) values (1)
    returning * into v_state;
  end if;

  v_cooldown_ms := v_state.cooldown_seconds * 1000;

  if v_state.last_feed_at is not null then
    v_elapsed_ms := extract(epoch from (now() - v_state.last_feed_at)) * 1000;
    if v_elapsed_ms < v_cooldown_ms then
      return query select
        true as cooldown,
        greatest(1, ceil(v_cooldown_ms - v_elapsed_ms)::int) as retry_after_ms,
        v_state.remaining_grams,
        v_state.max_capacity_grams,
        v_state.grams_per_portion,
        v_state.cooldown_seconds,
        v_state.simulation_mode,
        v_state.last_feed_at;
      return;
    end if;
  end if;

  update public.feeder_state as fs
  set
    remaining_grams = greatest(0, fs.remaining_grams - fs.grams_per_portion),
    last_feed_at = now(),
    updated_at = now()
  where fs.id = 1
  returning * into v_state;

  return query select
    false as cooldown,
    0 as retry_after_ms,
    v_state.remaining_grams,
    v_state.max_capacity_grams,
    v_state.grams_per_portion,
    v_state.cooldown_seconds,
    v_state.simulation_mode,
    v_state.last_feed_at;
end;
$$;

-- 4.2 refund_portion()
-- Refunds one portion (capped at max_capacity_grams) and resets last_feed_at to null
-- so a retry is not blocked by cooldown after a failed Tuya call.
create or replace function public.refund_portion()
returns public.feeder_state
language plpgsql
security definer
set search_path = public
as $$
declare
  v_state public.feeder_state%rowtype;
begin
  update public.feeder_state as fs
  set
    remaining_grams = least(fs.max_capacity_grams, fs.remaining_grams + fs.grams_per_portion),
    last_feed_at = null,
    updated_at = now()
  where fs.id = 1
  returning * into v_state;

  return v_state;
end;
$$;

-- 4.3 refill_hopper()
-- Resets remaining_grams to max_capacity_grams.
create or replace function public.refill_hopper()
returns public.feeder_state
language plpgsql
security definer
set search_path = public
as $$
declare
  v_state public.feeder_state%rowtype;
begin
  update public.feeder_state as fs
  set
    remaining_grams = fs.max_capacity_grams,
    updated_at = now()
  where fs.id = 1
  returning * into v_state;

  return v_state;
end;
$$;

